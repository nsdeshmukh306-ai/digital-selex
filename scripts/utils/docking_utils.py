import numpy as np
from typing import Dict, List, Optional, Tuple

from rdkit import Chem
from rdkit.Chem import AllChem, rdMolDescriptors


# ─── Ligand Preparation ───────────────────────────────────────────────────────

def smiles_to_sdf(smiles: str, out_path: str, name: str = "LIG") -> bool:
    """
    Convert SMILES to 3D-optimised SDF using RDKit ETKDG.
    Returns True on success, False on failure.
    """
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return False

    mol = Chem.AddHs(mol)
    params = AllChem.ETKDGv3()
    params.randomSeed = 42
    result = AllChem.EmbedMolecule(mol, params)
    if result == -1:
        # Fallback: distance geometry with random coords
        result = AllChem.EmbedMolecule(mol, AllChem.EmbedParameters())
    if result == -1:
        return False

    AllChem.MMFFOptimizeMolecule(mol, maxIters=500)
    mol.SetProp("_Name", name)

    writer = Chem.SDWriter(out_path)
    writer.write(mol)
    writer.close()
    return True


def sdf_to_pdbqt_ligand(sdf_path: str, pdbqt_path: str) -> bool:
    """
    Convert SDF to PDBQT using meeko.
    meeko handles AutoDock atom-type assignment and torsion detection.
    Returns True on success.
    """
    try:
        from meeko import MoleculePreparation, PDBQTWriterLegacy

        mol = Chem.SDMolSupplier(sdf_path, removeHs=False)[0]
        if mol is None:
            return False

        preparator = MoleculePreparation()
        mol_setups = preparator.prepare(mol)
        pdbqt_string, is_ok, err = PDBQTWriterLegacy.write_string(mol_setups[0])
        if not is_ok:
            return False

        with open(pdbqt_path, "w") as fh:
            fh.write(pdbqt_string)
        return True

    except Exception as e:
        print(f"  [WARN] meeko failed ({e}); falling back to obabel")
        return _sdf_to_pdbqt_obabel(sdf_path, pdbqt_path)


def _sdf_to_pdbqt_obabel(sdf_path: str, pdbqt_path: str) -> bool:
    """Fallback: use openbabel CLI to convert SDF → PDBQT."""
    cmd = ["obabel", sdf_path, "-O", pdbqt_path, "--partialcharge", "gasteiger"]
    try:
        r = subprocess.run(cmd, capture_output=True, timeout=30)
        return r.returncode == 0 and os.path.exists(pdbqt_path)
    except (subprocess.TimeoutExpired, FileNotFoundError):
        return False


